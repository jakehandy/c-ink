#!/usr/bin/env python3
"""Rasterize Inter into 1-bit bitmap fonts for the C-Ink renderer.

The output (firmware/components/cink_core/src/fonts_data.inc) is committed, so
building firmware never needs Python. Re-run this only when the font set
changes:

    python3 tools/fontgen.py --inter-dir /path/to/Inter/otf

Each glyph is a packed bitstream (no row padding). Advances and kerning are in
quarter pixels so long titles keep Inter's spacing instead of drifting by a
rounded pixel per glyph.
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont, features

TEXT = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x2022, 0x2026, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x2318,
]
DIGITS = [ord(c) for c in " 0123456789:$.,%+-kKMmhH/"]

# (identifier, file, pixel size, charset, threshold)
FONTS = [
    ("caption", "Inter-SemiBold.otf", 15, TEXT, 100),
    ("small", "Inter-Medium.otf", 18, TEXT, 104),
    ("body", "Inter-Regular.otf", 22, TEXT, 108),
    ("body_b", "Inter-SemiBold.otf", 22, TEXT, 112),
    ("sub", "Inter-Regular.otf", 26, TEXT, 116),
    ("tile", "Inter-SemiBold.otf", 20, TEXT, 108),
    ("title_s", "InterDisplay-Bold.otf", 36, TEXT, 124),
    ("title", "InterDisplay-Bold.otf", 46, TEXT, 128),
    ("big", "InterDisplay-Bold.otf", 72, TEXT, 128),
    ("huge", "InterDisplay-Bold.otf", 132, DIGITS, 128),
]

KERN_SET = [chr(c) for c in range(0x20, 0x7F)]


def has_glyph(path, cps):
    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        return set(cps)
    cmap = TTFont(path).getBestCmap()
    return {c for c in cps if c in cmap}


def pack_bits(mask, w, h, threshold):
    out = bytearray()
    acc = 0
    n = 0
    for y in range(h):
        for x in range(w):
            acc = (acc << 1) | (1 if mask.getpixel((x, y)) >= threshold else 0)
            n += 1
            if n == 8:
                out.append(acc)
                acc = 0
                n = 0
    if n:
        out.append(acc << (8 - n))
    return out


def build(ident, path, size, charset, threshold):
    layout = ImageFont.Layout.RAQM if features.check("raqm") else ImageFont.Layout.BASIC
    font = ImageFont.truetype(path, size, layout_engine=layout)
    ascent, descent = font.getmetrics()
    avail = has_glyph(path, charset)
    glyphs = []
    bitmap = bytearray()
    for cp in sorted(avail):
        ch = chr(cp)
        adv = round(font.getlength(ch) * 4)
        bbox = font.getbbox(ch, anchor="ls")
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
        if cp == 0x20 or w <= 0 or h <= 0:
            w = h = ox = oy = 0
            bits = b""
        else:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=font, fill=255, anchor="ls")
            ink = img.point(lambda v: 255 if v >= threshold else 0).getbbox()
            if ink is None:
                w = h = ox = oy = 0
                bits = b""
            else:
                img = img.crop(ink)
                ox, oy = bbox[0] + ink[0], bbox[1] + ink[1]
                w, h = img.size
                bits = pack_bits(img, w, h, threshold)
        assert w < 256 and h < 256 and -128 <= ox < 128 and -128 <= oy < 128 and adv < 65536, (ident, cp, w, h, ox, oy)
        glyphs.append((cp, w, h, ox, oy, adv, len(bitmap)))
        bitmap += bits

    kerns = []
    if charset is TEXT:
        names = [c for c in KERN_SET if ord(c) in avail]
        single = {c: font.getlength(c) for c in names}
        for a in names:
            for b in names:
                d = font.getlength(a + b) - single[a] - single[b]
                q = round(d * 4)
                if q != 0 and -128 <= q <= 127:
                    kerns.append(((ord(a) << 16) | ord(b), q))
        kerns.sort()
    return {
        "ident": ident, "size": size, "ascent": ascent, "descent": descent,
        "glyphs": glyphs, "bitmap": bitmap, "kerns": kerns,
        "src": os.path.basename(path),
    }


def emit(fonts, out):
    lines = [
        "// Generated by tools/fontgen.py from Inter (SIL Open Font License 1.1).",
        "// Do not edit by hand.",
        "",
    ]
    total = 0
    for f in fonts:
        i = f["ident"]
        bm = f["bitmap"]
        total += len(bm) + len(f["glyphs"]) * 12 + len(f["kerns"]) * 8
        lines.append(f"// {f['src']} @ {f['size']}px: {len(f['glyphs'])} glyphs, {len(bm)} bitmap bytes, {len(f['kerns'])} kern pairs")
        lines.append(f"static const uint8_t k_{i}_bits[] = {{")
        for j in range(0, len(bm), 24):
            lines.append("  " + ",".join(str(b) for b in bm[j:j + 24]) + ",")
        lines.append("  0};")
        lines.append(f"static const Glyph k_{i}_glyphs[] = {{")
        for g in f["glyphs"]:
            lines.append("  {%d,%d,%d,%d,%d,%d,%d}," % g)
        lines.append("};")
        if f["kerns"]:
            lines.append(f"static const Kern k_{i}_kerns[] = {{")
            for j in range(0, len(f["kerns"]), 8):
                lines.append("  " + "".join("{%du,%d}," % k for k in f["kerns"][j:j + 8]))
            lines.append("};")
            kref = f"k_{i}_kerns"
        else:
            kref = "nullptr"
        lines.append(
            f"const Font font_{i} = {{k_{i}_bits, k_{i}_glyphs, {kref}, "
            f"{len(f['glyphs'])}, {len(f['kerns'])}, {f['ascent']}, {f['descent']}, {f['size']}}};"
        )
        lines.append("")
    lines.append(f"// Total font data: ~{total} bytes")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return total


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inter-dir", default="/usr/share/fonts/opentype/inter")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..",
                    "firmware", "components", "cink_core", "src", "fonts_data.inc"))
    a = ap.parse_args()
    fonts = []
    for ident, fname, size, cs, th in FONTS:
        p = os.path.join(a.inter_dir, fname)
        if not os.path.exists(p):
            sys.exit(f"missing {p}")
        fonts.append(build(ident, p, size, cs, th))
    total = emit(fonts, a.out)
    print(f"wrote {a.out} ({total/1024:.1f} KiB of font data)")


if __name__ == "__main__":
    main()
